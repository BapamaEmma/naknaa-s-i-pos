export function getCategoryMap(categories: Category[]): Map<string, Category> {
  return new Map(categories.map((category) => [category.id, category]))
}

export function buildInventorySummary(variants: ProductVariant[]) {
  const totalStock = variants.reduce((sum, variant) => sum + variant.currentStock, 0)
  const inventoryValue = variants.reduce(
    (sum, variant) => sum + variant.currentStock * variant.costPrice,
    0,
  )
  const lowStockVariants = variants.filter(
    (variant) => variant.currentStock <= variant.minimumStock,
  ).length

  return { totalStock, inventoryValue, lowStockVariants }
}
